"""
Complex-script (Devanagari / Hindi) shaping helpers for the ReportLab PDFs.

Why this exists
---------------
ReportLab lays glyphs out one Unicode code point at a time.  Devanagari needs
OpenType shaping: the short-i matra ("ि") has to move in front of the consonant
it follows, conjuncts (क्ष ज्ञ श्र द्वा क्रां स्त्री ...) have to be substituted with
ligature glyphs, and marks have to be positioned.  Without shaping "विभाग"
prints as "वभाग" and "पुलिस" as "पुलसि".

ReportLab >= 5.0 can drive HarfBuzz itself (through ``uharfbuzz``), but only
where the caller asks for it:

* ``Paragraph`` text   -> ``ParagraphStyle(shaping=1)``       (use ``PARA_SHAPING``)
* canvas strings       -> :func:`draw_text` / :func:`text_width` below
* wrapping very long   -> :func:`fit_markup`
  words in narrow cells

Canvas strings get their own helper because ``canvas.drawString(shaping=True)``
only shapes when the optional ``rlbidi`` package is installed; otherwise
ReportLab silently ignores the flag.  Going through ``shapeStr`` ourselves
needs nothing beyond ``uharfbuzz``.

Mixed scripts
-------------
HarfBuzz is told one script per buffer, and ReportLab guesses it from the first
letter of a whitespace-delimited word.  A token such as "HQ-विभाग",
"Jaipur(जयपुर)" or a whole canvas line like "Generated by Stellura (स्टेल्यूरा)"
therefore gets shaped as Latin, and the Devanagari in it comes out unshaped.
Everything here shapes each Devanagari / non-Devanagari run separately, and
:func:`install` makes ReportLab's own Paragraph shaping do the same.

If ``uharfbuzz`` (or ReportLab >= 5) is missing, everything here degrades to
plain, unshaped ReportLab output so PDF export keeps working.
"""
import re
import unicodedata

try:  # pragma: no cover - exercised implicitly by the environment
    import uharfbuzz  # noqa: F401  (ReportLab imports it itself; this is the availability probe)
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import shapeStr

    SHAPING_AVAILABLE = True
except ImportError:  # uharfbuzz not installed, or ReportLab < 5
    pdfmetrics = None
    shapeStr = None
    SHAPING_AVAILABLE = False

# Pass as ``ParagraphStyle(..., **PARA_SHAPING)``.  Empty when shaping is not
# available so that an old ReportLab never sees an unknown style attribute.
PARA_SHAPING = {"shaping": 1} if SHAPING_AVAILABLE else {}

_DEVANAGARI_RE = re.compile(r"[\u0900-\u097f]")
# Maximal runs of Devanagari (plus joiners) and of everything else.
_RUN_RE = re.compile(r"[\u0900-\u097f\u200c\u200d]+|[^\u0900-\u097f\u200c\u200d]+")
_DEVA_OR_JOINER_RE = re.compile(r"[\u0900-\u097f\u200c\u200d]")
_VIRAMA = "\u094d"
_ZERO_WIDTH_JOINERS = "\u200c\u200d"


def contains_devanagari(text):
    """True if *text* holds at least one Devanagari character."""
    return isinstance(text, str) and bool(_DEVANAGARI_RE.search(text))


def _shapable(font_name):
    if not SHAPING_AVAILABLE:
        return False
    try:
        return bool(pdfmetrics.getFont(font_name).shapable)
    except Exception:
        return False


def _shape(text, font_name, font_size):
    """Shape *text*; returns a ReportLab ``ShapedStr`` (always carries shape data).

    Devanagari and non-Devanagari runs are shaped separately (see "Mixed
    scripts" above) and joined.
    """
    shaped = None
    for run in _RUN_RE.findall(text):
        part = shapeStr(run, font_name, font_size, force=True)
        shaped = part if shaped is None else shaped + part
    return shaped


def _shaped_width(shaped, font_size):
    # ShapeData.x_advance is expressed in 1/1000 em (ReportLab normalises the font).
    return sum(d.x_advance for d in shaped.__shapeData__) * font_size / 1000.0


def text_width(text, font_name, font_size):
    """Width in points of *text*, shaped when the font supports it.

    Use this instead of ``canvas.stringWidth`` for anything later drawn with
    :func:`draw_text`: conjuncts are narrower than the sum of their letters.
    """
    if not text:
        return 0.0
    if _shapable(font_name):
        return _shaped_width(_shape(text, font_name, font_size), font_size)
    return pdfmetrics.stringWidth(text, font_name, font_size) if pdfmetrics else 0.0


def draw_text(canvas, x, y, text, align="left"):
    """Draw *text* at (x, y) in the canvas' current font, shaped if possible.

    *align* is ``"left"``, ``"center"`` or ``"right"`` (the x coordinate is the
    left edge, the middle or the right edge of the text respectively), matching
    ``drawString`` / ``drawCentredString`` / ``drawRightString``.
    """
    # ``_fontname`` / ``_fontsize`` are what Canvas.drawString itself reads.
    font_name, font_size = canvas._fontname, canvas._fontsize
    if not text or not _shapable(font_name):
        if align == "center":
            canvas.drawCentredString(x, y, text)
        elif align == "right":
            canvas.drawRightString(x, y, text)
        else:
            canvas.drawString(x, y, text)
        return

    shaped = _shape(text, font_name, font_size)
    width = _shaped_width(shaped, font_size)
    if align == "center":
        x -= width / 2.0
    elif align == "right":
        x -= width
    tobj = canvas.beginText(x, y)
    tobj.textLine(shaped)
    canvas.drawText(tobj)


# ---------------------------------------------------------------------------
# Wrapping of words wider than their container
# ---------------------------------------------------------------------------

def clusters(text):
    """Split *text* into units that must never be separated across lines.

    A unit is a base character plus everything that attaches to it: combining
    marks (matras, nukta, anusvara, virama, ...), zero-width joiners, and the
    consonant that follows a virama (so a whole conjunct such as "स्त्री" stays
    together).  This is what a reader perceives as one "akshara".
    """
    cur = ""
    last = ""  # last character that is not a zero-width joiner
    for ch in text:
        attaches = bool(cur) and (
            unicodedata.category(ch).startswith("M")
            or ch in _ZERO_WIDTH_JOINERS
            or (last == _VIRAMA and "\u0900" <= ch <= "\u097f")
        )
        if attaches:
            cur += ch
        else:
            if cur:
                yield cur
            cur = ch
        if ch not in _ZERO_WIDTH_JOINERS:
            last = ch
    if cur:
        yield cur


def truncate(text, max_clusters):
    """First *max_clusters* clusters of *text* (never cuts a matra off its base)."""
    return "".join(list(clusters(text))[:max_clusters])


def _escape(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def fit_markup(text, font_name, font_size, max_width):
    """Return Paragraph markup for plain *text*, safe for narrow cells.

    * ``&``, ``<`` and ``>`` are escaped.
    * Any whitespace-delimited word whose (shaped) width exceeds *max_width* is
      broken with ``<br/>`` at akshara boundaries.

    ReportLab has its own long-word splitter, but it cuts between code points
    and, on shaped text, produces missing-glyph boxes.  Breaking at cluster
    boundaries ourselves means it never has to run for Devanagari.
    Text without Devanagari, or in a font that cannot shape, is only escaped.
    """
    text = "" if text is None else str(text)
    if (
        not max_width
        or max_width <= 0
        or not contains_devanagari(text)
        or not _shapable(font_name)
    ):
        return _escape(text)

    out = []
    for token in re.split(r"(\s+)", text):
        if not token or token.isspace():
            out.append(_escape(token))
            continue
        if text_width(token, font_name, font_size) <= max_width:
            out.append(_escape(token))
            continue
        lines, line = [], ""
        for unit in clusters(token):
            candidate = line + unit
            if line and text_width(candidate, font_name, font_size) > max_width:
                lines.append(line)
                line = unit
            else:
                line = candidate
        if line:
            lines.append(line)
        out.append("<br/>".join(_escape(piece) for piece in lines))
    return "".join(out)


# ---------------------------------------------------------------------------
# Script itemisation for ReportLab's own Paragraph shaping
# ---------------------------------------------------------------------------

def _split_mixed_script(word):
    """Split a ReportLab frag word at Devanagari / non-Devanagari boundaries.

    *word* is ``[width, (frag, text), ...]``.  Returns a list of frag words, or
    ``None`` when the word needs no splitting (single script, or it holds inline
    objects such as images, which are left to ReportLab).
    """
    pairs = word[1:]
    if any(hasattr(frag, "cbDefn") for frag, _ in pairs):
        return None
    text = "".join(t for _, t in pairs)
    flags = [bool(_DEVA_OR_JOINER_RE.match(ch)) for ch in text]
    if not any(flags) or all(flags):
        return None

    runs, run, run_kind, i = [], [], None, 0
    for frag, t in pairs:
        for ch in t:
            kind = flags[i]
            i += 1
            if run_kind is not None and kind != run_kind:
                runs.append(run)
                run = []
            run_kind = kind
            if run and run[-1][0] is frag:
                run[-1][1].append(ch)
            else:
                run.append((frag, [ch]))
    runs.append(run)

    cls = type(word)
    words = []
    for run in runs:
        tuples = [(frag, "".join(chars)) for frag, chars in run]
        width = sum(pdfmetrics.stringWidth(t, f.fontName, f.fontSize) for f, t in tuples)
        words.append(cls([width] + tuples))
    return words


def install():
    """Make ReportLab's Paragraph shaping handle words that mix scripts.

    Wraps ``reportlab.platypus.paragraph.shapeFragWord`` so a word is split at
    script boundaries, each piece shaped on its own, and the pieces put back
    together.  Safe to call repeatedly; any problem falls back to ReportLab's
    own behaviour.
    """
    if not SHAPING_AVAILABLE:
        return False
    try:
        from reportlab.platypus import paragraph as rl_paragraph
        from reportlab.pdfbase.ttfonts import makeShapedFragWord, ShapedFragWord
    except ImportError:
        return False
    original = rl_paragraph.shapeFragWord
    if getattr(original, "_stellura_itemized", False):
        return True

    def shape_frag_word(word, *args, **kwargs):
        try:
            if isinstance(word, ShapedFragWord):
                return word
            pieces = _split_mixed_script(word)
        except Exception:
            pieces = None
        if not pieces:
            return original(word, *args, **kwargs)
        shaped = [original(piece, *args, **kwargs) for piece in pieces]
        if not any(isinstance(piece, ShapedFragWord) for piece in shaped):
            return word  # nothing changed anywhere
        merged = [sum(piece[0] for piece in shaped)]
        for piece in shaped:
            merged.extend(tuple(t) for t in piece[1:])
        return makeShapedFragWord(word)(merged)

    shape_frag_word._stellura_itemized = True
    rl_paragraph.shapeFragWord = shape_frag_word
    return True


install()
